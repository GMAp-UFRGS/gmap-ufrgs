# Instala a classe gmap-ufrgs (cls, sty e logos) no TEXMFHOME do usuario,
# para poder usar \documentclass{gmap-ufrgs} em qualquer projeto sem copiar
# os arquivos manualmente.
#
# Uso: .\install.ps1

$ErrorActionPreference = "Stop"

$ScriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$Files = @("gmap-ufrgs.cls", "gmap-math.sty", "gmap-codigo.sty", "gmap-figuras.sty") |
    ForEach-Object { Join-Path $ScriptDir $_ }
$Logos = Get-ChildItem -Path (Join-Path $ScriptDir "fig") -Filter "logo-example-*.pdf" -ErrorAction SilentlyContinue

foreach ($f in $Files) {
    if (-not (Test-Path $f)) {
        Write-Error "Nao encontrei $f"
        exit 1
    }
}

$kpsewhich = Get-Command kpsewhich -ErrorAction SilentlyContinue
if (-not $kpsewhich) {
    Write-Error "kpsewhich nao encontrado. Instale o TeX Live/MiKTeX antes de continuar."
    exit 1
}

$TexmfHome = (& kpsewhich -var-value TEXMFHOME).Trim()
if ([string]::IsNullOrEmpty($TexmfHome)) {
    Write-Error "Nao foi possivel determinar o TEXMFHOME."
    exit 1
}

# Os logos ficam na mesma pasta da classe para que \includegraphics os encontre.
$DestDir = Join-Path $TexmfHome "tex\latex\gmap-ufrgs"
New-Item -ItemType Directory -Force -Path $DestDir | Out-Null
foreach ($f in $Files) { Copy-Item -Path $f -Destination $DestDir -Force }
foreach ($l in $Logos) { Copy-Item -Path $l.FullName -Destination $DestDir -Force }

Write-Host "gmap-ufrgs copiado para: $DestDir"

$initexmf = Get-Command initexmf -ErrorAction SilentlyContinue
$mktexlsr = Get-Command mktexlsr -ErrorAction SilentlyContinue
$texhash = Get-Command texhash -ErrorAction SilentlyContinue

if ($initexmf) {
    & initexmf --update-fndb
    Write-Host "Banco de nomes de arquivos atualizado (initexmf, MiKTeX)."
} elseif ($mktexlsr) {
    & mktexlsr $TexmfHome
    Write-Host "Banco de nomes de arquivos atualizado (mktexlsr)."
} elseif ($texhash) {
    & texhash $TexmfHome
    Write-Host "Banco de nomes de arquivos atualizado (texhash)."
} else {
    Write-Warning "Nenhum de initexmf/mktexlsr/texhash foi encontrado."
    Write-Warning "Atualize o banco de nomes de arquivos manualmente antes de usar a classe."
}

# TeXstudio: instala os arquivos de autocompletar (.cwl) para que os comandos
# da classe (\equipe, \figura, ...) nao aparecam como "comando desconhecido".
# Os .cwl gerados automaticamente pelo TeXstudio ficam desatualizados e sao
# apagados (ele os recria se precisar).
$TxsDir = Join-Path $env:APPDATA "texstudio"
if (Test-Path $TxsDir) {
    $CwlUser = Join-Path $TxsDir "completion\user"
    New-Item -ItemType Directory -Force -Path $CwlUser | Out-Null
    Copy-Item -Path (Join-Path $ScriptDir "texstudio\*.cwl") -Destination $CwlUser -Force
    $CwlAuto = Join-Path $TxsDir "completion\autogenerated"
    foreach ($c in @("gmap-ufrgs.cwl", "class-gmap-ufrgs.cwl", "gmap-math.cwl", "gmap-codigo.cwl", "gmap-figuras.cwl")) {
        $p = Join-Path $CwlAuto $c
        if (Test-Path $p) { Remove-Item -Path $p -Force }
    }
    Write-Host "Autocompletar do TeXstudio instalado em: $CwlUser (reinicie o TeXstudio)."
}

Write-Host "Instalacao concluida. Agora \documentclass{gmap-ufrgs} funciona em qualquer projeto."
