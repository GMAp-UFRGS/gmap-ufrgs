#!/bin/sh
# Instala a classe gmap-ufrgs (cls, sty e logos) no TEXMFHOME do usuario,
# para poder usar \documentclass{gmap-ufrgs} em qualquer projeto sem copiar
# os arquivos manualmente.
#
# Uso: ./install.sh

set -e

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"

for f in gmap-ufrgs.cls gmap-math.sty gmap-codigo.sty gmap-figuras.sty; do
    if [ ! -f "$SCRIPT_DIR/$f" ]; then
        echo "Erro: nao encontrei $f em $SCRIPT_DIR" >&2
        exit 1
    fi
done

if ! command -v kpsewhich >/dev/null 2>&1; then
    echo "Erro: kpsewhich nao encontrado. Instale o TeX Live/MiKTeX antes de continuar." >&2
    exit 1
fi

TEXMFHOME="$(kpsewhich -var-value TEXMFHOME)"
if [ -z "$TEXMFHOME" ]; then
    echo "Erro: nao foi possivel determinar o TEXMFHOME." >&2
    exit 1
fi

# Os logos ficam na mesma pasta da classe para que \includegraphics os encontre.
DEST_DIR="$TEXMFHOME/tex/latex/gmap-ufrgs"
mkdir -p "$DEST_DIR"
cp "$SCRIPT_DIR"/gmap-ufrgs.cls "$SCRIPT_DIR"/gmap-math.sty "$SCRIPT_DIR"/gmap-codigo.sty "$SCRIPT_DIR"/gmap-figuras.sty "$DEST_DIR"/
cp "$SCRIPT_DIR"/fig/gmap-logo-* "$DEST_DIR"/ 2>/dev/null || true

echo "gmap-ufrgs copiado para: $DEST_DIR"

if command -v mktexlsr >/dev/null 2>&1; then
    mktexlsr "$TEXMFHOME"
    echo "Banco de nomes de arquivos atualizado (mktexlsr)."
elif command -v texhash >/dev/null 2>&1; then
    texhash "$TEXMFHOME"
    echo "Banco de nomes de arquivos atualizado (texhash)."
elif command -v initexmf >/dev/null 2>&1; then
    initexmf --update-fndb
    echo "Banco de nomes de arquivos atualizado (initexmf, MiKTeX)."
else
    echo "Aviso: nenhum de mktexlsr/texhash/initexmf foi encontrado." >&2
    echo "Atualize o banco de nomes de arquivos manualmente antes de usar a classe." >&2
fi

# TeXstudio: instala os arquivos de autocompletar (.cwl) para que os comandos
# da classe (\equipe, \figura, ...) nao aparecam como "comando desconhecido".
# Os .cwl gerados automaticamente pelo TeXstudio ficam desatualizados e sao
# apagados (ele os recria se precisar).
TXS_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/texstudio"
if [ -d "$TXS_DIR" ]; then
    mkdir -p "$TXS_DIR/completion/user"
    cp "$SCRIPT_DIR"/texstudio/*.cwl "$TXS_DIR/completion/user/"
    for c in gmap-ufrgs.cwl class-gmap-ufrgs.cwl gmap-math.cwl gmap-codigo.cwl gmap-figuras.cwl; do
        rm -f "$TXS_DIR/completion/autogenerated/$c"
    done
    echo "Autocompletar do TeXstudio instalado em: $TXS_DIR/completion/user (reinicie o TeXstudio)."
fi

echo "Instalacao concluida. Agora \\documentclass{gmap-ufrgs} funciona em qualquer projeto."
